def _popcount_table(r):
    return np.array([bin(c).count("1") for c in range(2**r)], dtype=np.int16)


def _wlp(cols, r, k):
    """Word length patterns (A3, ..., Ak) of a batch of designs, given their generator columns."""
    n, p = cols.shape
    xor = np.zeros((n, 1), dtype=np.int64)
    for i in range(p):
        xor = np.concatenate([xor, xor ^ cols[:, i : i + 1]], axis=1)
    sizes = _popcount_table(p)
    lengths = _popcount_table(r)[xor[:, 1:]] + sizes[1:]
    return np.stack([(lengths == length).sum(axis=1) for length in range(3, k + 1)], axis=1)


def _first_lex_min(keys):
    """Index of the first lexicographically smallest row."""
    idx = np.arange(len(keys))
    for j in range(keys.shape[1]):
        col = keys[idx, j]
        idx = idx[col == col.min()]
    return idx[0]


def search(k1, k2, r1, r2):
    """Minimum aberration design: (wlp, wp columns, sp columns)."""
    r, k = r1 + r2, k1 + k2
    p1, p2 = k1 - r1, k2 - r2
    units = {1 << i for i in range(r)}
    wp_avail = [c for c in range(1, 2**r1) if c not in units]
    sp_avail = [c for c in range(2**r1, 2**r) if c not in units]
    choices = (wp + sp for wp, sp in product(combinations(wp_avail, p1), combinations(sp_avail, p2)))
    batch = CHUNK >> (p1 + p2)

    best = None
    while True:
        chunk = np.array([c for _, c in zip(range(batch), choices, strict=False)], dtype=np.int64)
        if len(chunk) == 0:
            break
        wlp = _wlp(chunk, r, k)
        i = _first_lex_min(wlp)
        candidate = (tuple(int(a) for a in wlp[i]), tuple(int(c) for c in chunk[i]))
        if best is None or candidate[0] < best[0]:
            best = candidate
    if best is None:
        return None
    return best[0], best[1][:p1], best[1][p1:]


def _bits(c):
    return tuple(i for i in range(c.bit_length()) if c >> i & 1)


def main():
    entries = []
    start = time.time()
    for n_runs, k_max in RANGE.items():
        r = n_runs.bit_length() - 1
        for k in range(r + 1, k_max + 1):
            for k1 in range(1, k):
                k2 = k - k1
                for r1 in range(1, min(k1, r - 1) + 1):
                    r2 = r - r1
                    if r2 > k2:
                        continue
                    result = search(k1, k2, r1, r2)
                    if result is None:
                        continue
                    wlp, wp, sp = result
                    gens = [_bits(c) for c in wp + sp]
                    entries.append((n_runs, k, k1, k2, r1, wlp, gens))
            print(f"{n_runs} runs, {k} factors: {time.time() - start:.0f} s", flush=True)

    range_text = ", ".join(f"{n} runs up to {k} factors" for n, k in RANGE.items())
    lines = [HEADER.format(range_text=range_text)]
    for n_runs, k, k1, k2, r1, wlp, gens in entries:
        p1, p2 = k1 - r1, k - k1 - ((n_runs.bit_length() - 1) - r1)
        lines.append(f"    ({k1}, {k2}, {n_runs}, {2**r1}): ({wlp}, {gens}),  # {k1}.{k2}.{p1}.{p2}\n")
    lines.append("}\n")
    OUTPUT.write_text("".join(lines), encoding="utf-8")
    print(f"{len(entries)} designs written to {OUTPUT}")


if __name__ == "__main__":
    main()
